#pragma once

#include "clock.h"

namespace celeris {
    /*
        Траектория задаёт функцию f: Timestamp -> Y.

        Поведенческий контракт:
        - При неизменных данных, определяющих траекторию, результат зависит
          только от timestamp. Любые повторные запросы одного времени должны
          возвращать одно и то же значение, в том числе после запросов других
          времён и независимо от порядка и количества предыдущих обращений.
        - Обращение к траектории не изменяет саму определяемую функцию.
          Внутренние изменения, включая заполнение кэша, допустимы, если они
          сохраняют это свойство.
        - Если исходные данные явно изменены средствами конкретной реализации,
          они могут определять новую функцию. Гарантия относится к каждой
          фиксированной версии исходных данных отдельно.

        Совпадение результатов означает совпадение значений состояния Y,
        а не адресов возвращаемых объектов. Интерфейс не требует наличия
        operator== у Y; способ сравнения в тестах выбирается для данного Y.

        Сигнатуры и динамический полиморфизм проверяются компилятором.
        Поведенческий контракт является обязательством реализаций;
        конечный набор тестов проверяет лишь выбранные истории обращений.
    */
    template<class Y>
    class TrajectoryInterface {
    public:
        using Timestamp = simulation::Timestamp;

        virtual ~TrajectoryInterface() = default;

        /*
            NVI: публичная операция делегирует вычисление реализации.
            Отсутствие const разрешает внутреннее кэширование.
        */
        [[nodiscard]]
        Y operator()(Timestamp timestamp) {
            return evaluate_impl(timestamp);
        }

    private:
        virtual Y evaluate_impl(Timestamp timestamp) = 0;
    };
}
