#pragma once

#include <concepts>
#include <optional>
#include <utility>

#include "clock.h"
#include "invalidation_region.h"

namespace celeris {
    /*
        Кэш вычисленных значений, Y имеет семантику копируемого значения.
        find(t): отсутствующее значение либо копия последнего store(t, y).
        Отсутствие выражается nullopt, а не специальным значением Y.

        store(t, y): заменяет прежнее значение ключа. Кэш вправе вытеснять записи
        и даже не сохранять новую. Но попадание после store не может возвращать
        прежнее или выдуманное значение. Кэш без хранения является моделью.

        invalidate(region): после УСПЕХА нет записей, для которых region(t)=true.
        Дополнительное вытеснение допустимо. При исключении допустимо частичное
        удаление. Предикат не меняет кэш через побочный канал; его заимствования
        действительны в течение операции. Интервальное ускорение необязательно.

        При исключениях кэш остаётся работоспособным: может потерять записи,
        но оставшиеся значения — целиком прежние либо полностью записанное y.
        Частично изменённые значения и записи для других ключей недопустимы.

        Чтение/копирование результатов не предоставляет обходного пути изменения
        сохранённых логических значений. Внутреннее обслуживание/вытеснение при
        чтении допустимо. Владение изменениями кэша в композиции — у адаптера.
        Только адаптер отвечает за соответствие записей текущей версии f.

        Обязателен приём базового динамического региона. Перегрузки для более
        сильных статических типов допустимы. Концепт не требует порядка ключей,
        итераторов, конструктора по умолчанию, стабильности ссылок, operator==
        у Y, конкретной ёмкости, асимптотики или потокобезопасности.
        Форма операций не доказывает эти поведенческие гарантии.
    */
    template<class Cache, class Y>
    concept trajectory_cache =
        std::copy_constructible<Y> &&
        requires(
            Cache& cache,
            const Cache& readable,
            simulation::Timestamp timestamp,
            Y value,
            const InvalidationRegionInterface& region)
        {
            { readable.find(timestamp) } -> std::same_as<std::optional<Y>>;
            { cache.store(timestamp, std::move(value)) } -> std::same_as<void>;
            { cache.invalidate(region) } -> std::same_as<void>;
        };
}
